"""Samples of the HD text's two faces for the in-game font choice (Options > HD text > A): KHMenu (the game's, in
port/assets/fonts) and the system's (Segoe UI here, as Windows shows it). White letters with the dark outline the HD
text uses, on transparency, 2 rows x 1280x160 (drawn at the screen's resolution). Writes port/include/port/font_samples_png.inc.

    python port/tools/gen_font_samples.py
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'port/include/port/font_samples_png.inc'
TEXT = 'Sora, Riku · ¿Recuerdas?'
FACES = [ROOT / 'port/assets/fonts/KHMenu.otf', Path('C:/Windows/Fonts/segoeui.ttf')]
W, H, S = 1280, 160, 2


def sample(face):
    font = ImageFont.truetype(str(face), 88 * S)
    big = Image.new('L', (W * S, H * S), 0)
    d = ImageDraw.Draw(big)
    box = d.textbbox((0, 0), TEXT, font=font)
    x = (W * S - (box[2] - box[0])) // 2 - box[0]
    y = (H * S - (box[3] - box[1])) // 2 - box[1]
    d.text((x, y), TEXT, fill=255, font=font)
    ink = big.resize((W, H), Image.LANCZOS)
    edge = ink.filter(ImageFilter.MaxFilter(9))
    img = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    img.paste((40, 32, 56, 235), (0, 0), edge)
    img.paste((255, 255, 255, 255), (0, 0), ink)
    return img


def main():
    sheet = Image.new('RGBA', (W, H * len(FACES)), (0, 0, 0, 0))
    for i, face in enumerate(FACES):
        sheet.alpha_composite(sample(face), (0, i * H))
    path = ROOT / 'build/font_samples.png'
    path.parent.mkdir(exist_ok=True)
    sheet.save(path, optimize=True)
    data = path.read_bytes()
    lines = ['/* Generated by port/tools/gen_font_samples.py: KHMenu above, the system\'s face below, 1280x160 each. */']
    for i in range(0, len(data), 24):
        lines.append(','.join(str(b) for b in data[i:i + 24]) + ',')
    OUT.write_text('\n'.join(lines) + '\n', encoding='ascii', newline='\n')
    print(path, len(data), 'bytes')


if __name__ == '__main__':
    main()
