def generate(inventories):
 text=['/* Generated by preliminar_v1_recipes.py; source coordinates only. */']
 seen=set()
 for inventory in inventories:
  rows=json.loads(Path(inventory).read_text())
  for row in rows:
   n=int(row['symbol'][-3:])
   if n not in RECIPES:continue
   w,h,L,R,dl,dr,top,bottom,layers=RECIPES[n]
   for layer,hs in row['hashes'].items():
    bg=int(layer[-1]);key=(hs,bg)
    if key in seen:continue
    seen.add(key);repeat=bg==3 or bg in layers
    vals=[n,bg,row['width']//256,row['height']//256,w,h,*L,*R,dl,dr]
    vals+=list(top if top and bg==3 else (0,0,0,0));vals+=list(bottom if bottom and bg==3 else (0,0,0,0));vals+=[int(repeat),int(n in READY)]
    text.append('    {0x%08xu, {%s}}, /* %s %s */'%(hs,','.join(map(str,vals)),row['symbol'],layer))
 target=ROOT/'port/include/port/port_preliminar_v1_data.inc';target.write_text('\n'.join(text)+'\n')
