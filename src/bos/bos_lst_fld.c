void BosLstFldDarkenPalette(u16* dst, u16* src, s32 count, s32 level) {
    s32 dark;
    s32 mask;
    s32 color;

    level = level <= 31 ? 31 & ~level : 0;
    count--;

    while (count != -1) {
        color = src[count];
        mask = 0x1F;
        dark = (color & mask) * level >> 5 & mask;
        mask <<= 5;
        dark |= (color & mask) * level >> 5 & mask;
        mask <<= 5;
        dark |= (color & mask) * level >> 5 & mask;
        dst[count] = dark;
        count--;
    }
}

